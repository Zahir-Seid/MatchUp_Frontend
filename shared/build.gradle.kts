// Every Kotlin compilation (metadata, Android, Wasm) needs the generated
// config on the source path before it can run.
tasks.matching { task ->
    task.name.startsWith("compile") || task.name.startsWith("assemble")
}.configureEach {
    dependsOn(generateAppConfig)
}

