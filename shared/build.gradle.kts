// ---------------------------------------------------------------------------
// Build-time client configuration
//
// The app ships to Android and to a browser, so it cannot read a backend-style
// .env at runtime. Gradle reads .env (or local.properties / the process env)
// and generates a tiny Kotlin object that is compiled into both targets.
// ---------------------------------------------------------------------------

fun readDotEnv(file: File): Map<String, String> {
    if (!file.exists()) return emptyMap()
    return file.readLines()
        .asSequence()
        .map { it.trim() }
        .filter { it.isNotEmpty() && !it.startsWith("#") }
        .mapNotNull { line ->
            val idx = line.indexOf('=')
            if (idx <= 0) null
            else line.substring(0, idx).trim() to line.substring(idx + 1).trim()
                .removeSurrounding("\"")
                .removeSurrounding("'")
        }
        .toMap()
}

val rootDir = rootProject.projectDir
val dotEnv = readDotEnv(File(rootDir, ".env"))
val localProperties = Properties().also { props ->
    val file = File(rootDir, "local.properties")
    if (file.exists()) file.inputStream().use(props::load)
}
fun configValue(key: String, default: String = ""): String =
    localProperties.getProperty(key)
        ?: System.getenv(key)
        ?: dotEnv[key]
        ?: default

fun String.kotlinLiteral(): String = buildString {
    append('"')
    this@kotlinLiteral.forEach { ch ->
        when (ch) {
            '\\' -> append("\\\\")
            '"' -> append("\\\"")
            '$' -> append("\\$")
            '\n' -> append("\\n")
            '\r' -> append("\\r")
            else -> append(ch)
        }
    }
    append('"')
}

val generatedConfigDir = layout.buildDirectory.dir("generated/matchupConfig/commonMain/kotlin")

val generateAppConfig = tasks.register("generateAppConfig") {
    val androidBase = configValue("API_BASE_URL_ANDROID", "http://10.0.2.2:8082/v1")
    val webBase = configValue("API_BASE_URL_WEB", "/v1")
    val googleClient = configValue("GOOGLE_WEB_CLIENT_ID")
    val vapid = configValue("WEB_PUSH_VAPID_PUBLIC_KEY")
    val enableFcm = configValue("ENABLE_FCM", "false")
    val version = configValue("APP_VERSION", "1.0.0")

    inputs.property("androidBase", androidBase)
    inputs.property("webBase", webBase)
    inputs.property("googleClient", googleClient)
    inputs.property("vapid", vapid)
    inputs.property("enableFcm", enableFcm)
    inputs.property("version", version)
    outputs.dir(generatedConfigDir)

    doLast {
        val out = generatedConfigDir.get().asFile
        // Wipe the output directory so a renamed or removed key never leaves a
        // stale source file behind (it would be compiled twice).
        out.deleteRecursively()
        // Keep the package directory layout in sync with the declared package
        // so Android Studio shows the file under et.matchup.app.config.
        val packageDir = File(out, "et/matchup/app/config")
        packageDir.mkdirs()
        File(packageDir, "GeneratedConfig.kt").writeText(
            """
            package et.matchup.app.config

            // Generated by :shared:generateAppConfig from .env, local.properties,
            // or the process environment. Do not edit by hand.
            object GeneratedConfig {
                const val API_BASE_URL_ANDROID = ${androidBase.kotlinLiteral()}
                const val API_BASE_URL_WEB = ${webBase.kotlinLiteral()}
                const val GOOGLE_WEB_CLIENT_ID = ${googleClient.kotlinLiteral()}
                const val WEB_PUSH_VAPID_PUBLIC_KEY = ${vapid.kotlinLiteral()}
                const val ENABLE_FCM = ${enableFcm.kotlinLiteral()}
                const val APP_VERSION = ${version.kotlinLiteral()}
            }
            """.trimIndent(),
        )
    }
}

// The generated file is compiled into every target, so the directory carries a
// dependency on the generator task. KGP propagates it to the compile tasks.
